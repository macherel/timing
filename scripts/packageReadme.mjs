/**
 * Texts of the README files put in the release packages: README.txt (English), LISEZMOI.txt (French) and
 * LIESMICH.txt (German). Keep the languages in step, and the page and button names in step with frontend/src/locales.
 */

/** File name -> text, for one platform. */
export function readmeFiles({ version, nodeVersion, platformName, dataDir }) {
    const isWindows = platformName.startsWith('win');
    const ctx = {
        version,
        nodeVersion,
        platformName,
        dataDir,
        isWindows,
        start: isWindows ? 'timing.cmd' : './timing.sh',
        diagnose: isWindows ? 'diagnose.cmd' : './diagnose.sh',
    };
    const newline = isWindows ? '\r\n' : '\n';
    // Notepad shows accented letters right with a byte order mark
    const bom = isWindows ? '\uFEFF' : '';
    const format = (lines) => lines.filter((line) => line !== null).join('\n').replace(/\n/g, newline);
    return {
        'README.txt': format(english(ctx)),
        'LISEZMOI.txt': bom + format(french(ctx)),
        'LIESMICH.txt': bom + format(german(ctx)),
    };
}

